"""Generate all local MQTT credentials and hash the Mosquitto password DB.

The script intentionally rotates every account together. It never prints a
password. Docker is used only to run the official ``mosquitto_passwd`` tool,
so no host Mosquitto installation is required.
"""

from __future__ import annotations

import argparse
import os
import re
import secrets
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Iterable


RANDOM_BYTES = 32
ENV_SAFE_TOKEN = re.compile(r"^[A-Za-z0-9_-]+$")

# (username environment variable, password environment variable, fixed username)
ACCOUNTS: tuple[tuple[str, str, str], ...] = (
    ("MQTT_SMART_LOCK_USERNAME", "MQTT_SMART_LOCK_PASSWORD", "device_smart_lock_01"),
    (
        "MQTT_RFID_SCANNER_USERNAME",
        "MQTT_RFID_SCANNER_PASSWORD",
        "device_rfid_scanner_01",
    ),
    (
        "MQTT_AIR_QUALITY_USERNAME",
        "MQTT_AIR_QUALITY_PASSWORD",
        "device_air_quality_01",
    ),
    (
        "MQTT_POWER_METER_USERNAME",
        "MQTT_POWER_METER_PASSWORD",
        "device_power_meter_01",
    ),
    (
        "MQTT_DECOY_TWIN_USERNAME",
        "MQTT_DECOY_TWIN_PASSWORD",
        "device_decoy_twin_01",
    ),
    (
        "MQTT_ATTACK_CONTROLLER_USERNAME",
        "MQTT_ATTACK_CONTROLLER_PASSWORD",
        "attack_controller",
    ),
    ("MQTT_BACKEND_USERNAME", "MQTT_BACKEND_PASSWORD", "backend"),
    ("MQTT_OBSERVER_USERNAME", "MQTT_OBSERVER_PASSWORD", "observer"),
)


def generate_credentials() -> dict[str, str]:
    credentials = {
        username: secrets.token_urlsafe(RANDOM_BYTES)
        for _, _, username in ACCOUNTS
    }
    if len(set(credentials.values())) != len(ACCOUNTS):
        raise RuntimeError("Credential generator produced a duplicate token")
    if not all(ENV_SAFE_TOKEN.fullmatch(value) for value in credentials.values()):
        raise RuntimeError("Credential generator produced a non-environment-safe token")
    return credentials


def render_env(credentials: dict[str, str]) -> str:
    lines = [
        "# Generated by sim/setup_credentials.py. Never commit this file.",
        "# Rotation replaces every MQTT account together.",
        "# Host port 1884 avoids the machine's existing native Mosquitto service.",
        "",
        "MQTT_HOST_PORT=1884",
        "",
    ]
    for username_key, password_key, username in ACCOUNTS:
        lines.extend(
            (
                f"{username_key}={username}",
                f"{password_key}={credentials[username]}",
                "",
            )
        )
    return "\n".join(lines).rstrip() + "\n"


def render_plain_password_file(credentials: dict[str, str]) -> str:
    return "".join(f"{username}:{credentials[username]}\n" for _, _, username in ACCOUNTS)


def hash_password_file_with_docker(
    *,
    docker_executable: str,
    image: str,
    password_file: Path,
) -> None:
    mount = f"{password_file.parent.resolve()}:/work"
    command = [
        docker_executable,
        "run",
        "--rm",
        "--entrypoint",
        "mosquitto_passwd",
        "--volume",
        mount,
        image,
        "-U",
        f"/work/{password_file.name}",
    ]
    completed = subprocess.run(
        command,
        check=False,
        capture_output=True,
        text=True,
    )
    if completed.returncode != 0:
        safe_error = completed.stderr.strip() or completed.stdout.strip() or "unknown error"
        raise RuntimeError(f"mosquitto_passwd container failed: {safe_error}")


def verify_hashed_password_file(
    password_file: Path,
    credentials: dict[str, str],
) -> None:
    content = password_file.read_text(encoding="utf-8")
    lines = [line for line in content.splitlines() if line]
    if len(lines) != len(ACCOUNTS):
        raise RuntimeError("Hashed password database has an unexpected account count")
    records: dict[str, str] = {}
    for line in lines:
        if ":" not in line:
            raise RuntimeError("Hashed password database contains a malformed record")
        username, password_hash = line.split(":", maxsplit=1)
        records[username] = password_hash
    for _, _, username in ACCOUNTS:
        if username not in records:
            raise RuntimeError(f"Hashed password database is missing {username}")
        if credentials[username] in content:
            raise RuntimeError("Plaintext password remained in the hashed database")
        if not records[username].startswith("$"):
            raise RuntimeError(f"Password record for {username} is not recognizably hashed")


def install_pair_atomically(
    staged_password_file: Path,
    staged_env_file: Path,
    target_password_file: Path,
    target_env_file: Path,
) -> None:
    targets = (
        (staged_password_file, target_password_file),
        (staged_env_file, target_env_file),
    )
    backups: list[tuple[Path, Path | None]] = []
    installed: list[Path] = []

    try:
        for index, (staged, target) in enumerate(targets):
            target.parent.mkdir(parents=True, exist_ok=True)
            backup: Path | None = None
            if target.exists():
                backup = staged.parent / f"backup-{index}"
                shutil.copy2(target, backup)
            backups.append((target, backup))
            os.replace(staged, target)
            installed.append(target)

        _best_effort_private_mode(target_env_file)
        _best_effort_private_mode(target_password_file)
    except Exception:
        for target, backup in reversed(backups):
            try:
                if backup is not None and backup.exists():
                    os.replace(backup, target)
                elif target in installed and target.exists():
                    target.unlink()
            except OSError:
                pass
        raise


def _best_effort_private_mode(path: Path) -> None:
    try:
        path.chmod(0o600)
    except OSError:
        # Windows/Docker Desktop permission semantics are verified later by the
        # Docker-dependent Phase 2 checks.
        pass


def _write_private(path: Path, content: str) -> None:
    path.write_text(content, encoding="utf-8", newline="\n")
    _best_effort_private_mode(path)


def _existing_outputs(paths: Iterable[Path]) -> list[Path]:
    return [path for path in paths if path.exists()]


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--rotate",
        action="store_true",
        help="Replace all existing MQTT credentials after the lab has been stopped.",
    )
    parser.add_argument(
        "--image",
        default="eclipse-mosquitto:2",
        help="Mosquitto image used only for the mosquitto_passwd tool.",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    repository_root = Path(__file__).resolve().parents[1]
    target_env = repository_root / "sim" / ".env"
    generated_dir = repository_root / "sim" / "broker" / "generated"
    target_password_file = generated_dir / "passwd"

    existing = _existing_outputs((target_env, target_password_file))
    if existing and not args.rotate:
        locations = ", ".join(str(path.relative_to(repository_root)) for path in existing)
        print(
            f"Refusing to replace existing credentials ({locations}). "
            "Stop the lab and rerun with --rotate.",
            file=sys.stderr,
        )
        return 2

    docker_executable = shutil.which("docker")
    if docker_executable is None:
        print(
            "Docker is required to hash the Mosquitto password database but is not on PATH.",
            file=sys.stderr,
        )
        return 2

    generated_dir.mkdir(parents=True, exist_ok=True)
    staging_path = Path(tempfile.mkdtemp(prefix=".credential-stage-", dir=generated_dir))
    try:
        credentials = generate_credentials()
        staged_password_file = staging_path / "passwd"
        staged_env_file = staging_path / "sim.env"
        _write_private(staged_password_file, render_plain_password_file(credentials))
        _write_private(staged_env_file, render_env(credentials))

        hash_password_file_with_docker(
            docker_executable=docker_executable,
            image=args.image,
            password_file=staged_password_file,
        )
        verify_hashed_password_file(staged_password_file, credentials)
        install_pair_atomically(
            staged_password_file,
            staged_env_file,
            target_password_file,
            target_env,
        )
    except Exception as exc:
        print(f"Credential generation failed without replacing active outputs: {exc}", file=sys.stderr)
        return 1
    finally:
        shutil.rmtree(staging_path, ignore_errors=True)

    print("Generated all 8 MQTT accounts without printing passwords.")
    print("Client variables: sim/.env")
    print("Mosquitto database: sim/broker/generated/passwd")
    return 0


if __name__ == "__main__":
    sys.exit(main())
